r"""What the two Alembic chains are and how to run one.

Shared by `test_migration_ownership.py`, which runs each chain against a
composed database, `test_migration_allowlists.py`, which checks the allowlists
and the wiring without needing one, `test_migration_chain.py`, which checks the
shape of each chain, and `test_migration_upgrade.py`, which applies one.
"""

